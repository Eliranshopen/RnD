await p.waitForTimeout(800);
console.log('body', (await p.evaluate(() => document.body.innerText.slice(0, 200))).replace(/\n/g, ' | '));
const items = [await p.getByText('revchat').first()];
console.log('items', items.length);
if (items.length) await items[0].click();
await p.waitForTimeout(800);
console.log('agent visible', await p.isVisible('#agent-input'));
await p.fill('#agent-input', '<img src=x onerror=alert(1)> **bold**\n- a');
await p.keyboard.press('Enter');
await p.waitForTimeout(800);
console.log('after enter value=', JSON.stringify(await p.inputValue('#agent-input')), 'msgs', (await p.$$('#agent-log .agent__msg')).length);
console.log('img injected', (await p.$$('#agent-log img')).length, 'dialogs', dialogs, 'b', (await p.$$('#agent-log b')).length);
