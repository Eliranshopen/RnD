"""Regenerate .wt/platform-ui-ux/CHANGES.md from manifest.json + changes-notes.json.

Dev scaffolding (outside files/, never copied back). Deterministic: sorted by path.
Usage (from C:\\RnD): python .wt/platform-ui-ux/tools/changes.py
"""
import hashlib, json, os, sys

WT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
WT = os.path.normpath(WT)
man = json.load(open(os.path.join(WT, "manifest.json"), encoding="utf-8"))
notes_p = os.path.join(WT, "tools", "changes-notes.json")
notes = json.load(open(notes_p, encoding="utf-8")) if os.path.exists(notes_p) else {}


def sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


groups = {"changed": [], "new": [], "unchanged": [], "missing": []}
for e in sorted(man["files"], key=lambda e: e["path"]):
    p = e["path"]
    cp = os.path.join(WT, "files", p)
    at_open = e.get("sha256_at_open")
    if not os.path.exists(cp):
        groups["missing"].append(p)
    elif at_open is None:
        groups["new"].append(p)
    elif sha(cp) != at_open:
        groups["changed"].append(p)
    else:
        groups["unchanged"].append(p)

out = ["# CHANGES — platform-ui-ux (what is on this branch, for Eliran)",
       "<!-- generated by .wt/platform-ui-ux/tools/changes.py; summaries from tools/changes-notes.json -->",
       "",
       f"changed: {len(groups['changed'])} · new: {len(groups['new'])} · unchanged: {len(groups['unchanged'])} · not yet written: {len(groups['missing'])}",
       "Nothing here is live. Copy-back is card 20, only on Eliran's \"good\"; any deploy is its own go (root §9).",
       ""]
for g, title in (("changed", "changed"), ("new", "new"), ("unchanged", "unchanged"), ("missing", "new, not yet written")):
    for p in groups[g]:
        out.append(f"## {title}: `{p}`")
        out.append(notes.get(p, "—"))
        out.append("")
open(os.path.join(WT, "CHANGES.md"), "w", encoding="utf-8", newline="\n").write("\n".join(out))
print({k: len(v) for k, v in groups.items()})
